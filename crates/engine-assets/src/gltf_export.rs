//! Writing a model back out as a `.glb`: the other half of [`crate::gltf_import`].
//!
//! ```text
//!  ModelAsset ──► export_glb ──► bytes ──► assets/generated/**/x.glb
//!                                            │
//!                                            └─► import_glb ──► ModelAsset
//! ```
//!
//! # Why an exporter exists at all
//!
//! This project's starter content is authored in code, and content authored in code is
//! content the editor cannot browse, an artist cannot replace and the asset validator cannot
//! measure. Writing it to disk as glTF turns it into ordinary content: the asset browser
//! discovers a file, the importer reads it through the one path every model goes down, and
//! replacing a generated rock with a sculpted one is dropping a file with the same name over
//! it. Nothing in the engine has to know which of the two it got.
//!
//! # What is written and what is not
//!
//! Written: level 0 geometry — positions, normals, texture coordinates and indices — every
//! material, and every texture, as PNG inside the binary chunk.
//!
//! Not written: levels of detail, skeletons, animation clips, vertex colours and tangents.
//! glTF has no level-of-detail concept without a vendor extension, a starter prop has no
//! skeleton, and a tangent is regenerated by [`crate::mesh::SubMesh::new`] at import from the
//! geometry it belongs to — writing one would be storing a derived value that the importer
//! recomputes anyway. A model that round-trips through here therefore comes back with one
//! level of detail, which is what every artist-delivered `.glb` in this project already has.
//!
//! # Cost model
//!
//! Development only, run by the asset generator, never by the game: one pass over the
//! geometry, one PNG encode per texture. Nothing here runs in a frame.

use std::io::Write as _;

use engine_core::math::Vec3;

use crate::error::AssetError;
use crate::material::SurfaceClass;
use crate::mesh::Geometry;
use crate::model::ModelAsset;
use crate::texture::{TextureAsset, TextureFormat};

/// glTF's `FLOAT` component type.
const FLOAT: u32 = 5126;
/// glTF's `UNSIGNED_INT` component type.
const UNSIGNED_INT: u32 = 5125;
/// glTF's `ARRAY_BUFFER` buffer-view target.
const ARRAY_BUFFER: u32 = 34_962;
/// glTF's `ELEMENT_ARRAY_BUFFER` buffer-view target.
const ELEMENT_ARRAY_BUFFER: u32 = 34_963;

/// The GLB container's magic number, `"glTF"` little-endian.
const MAGIC: u32 = 0x4654_6C67;
/// The GLB chunk type of the JSON chunk, `"JSON"`.
const CHUNK_JSON: u32 = 0x4E4F_534A;
/// The GLB chunk type of the binary chunk, `"BIN\0"`.
const CHUNK_BIN: u32 = 0x004E_4942;

/// Writes `model` as a binary glTF document.
///
/// # Errors
///
/// [`AssetError::Invalid`] for a model with no level of detail, and
/// [`AssetError::Malformed`] if a texture cannot be PNG-encoded — which means a texture whose
/// texel count and dimensions disagree, and [`TextureAsset::new`] already refuses those.
pub fn export_glb(model: &ModelAsset) -> Result<Vec<u8>, AssetError> {
    let Some(lod) = model.lod0() else {
        return Err(AssetError::invalid(
            &model.name,
            "lods",
            "a model with no geometry cannot be written as glTF",
        ));
    };

    let mut bin: Vec<u8> = Vec::with_capacity(64 * 1_024);
    let mut views = Views::default();
    let mut accessors: Vec<String> = Vec::new();
    let mut meshes: Vec<String> = Vec::new();
    let mut nodes: Vec<String> = Vec::new();

    for submesh in &lod.submeshes {
        let Geometry::Static(vertices) = &submesh.geometry else {
            return Err(AssetError::Unsupported {
                model: model.name.clone(),
                feature: "writing skinned geometry as glTF".to_owned(),
            });
        };
        if vertices.is_empty() || submesh.indices.is_empty() {
            continue;
        }

        // Positions, and the bounds glTF requires an author to state for them. Every other
        // accessor may omit min and max; POSITION may not, because a loader is allowed to
        // build the scene's bounds without reading a single vertex.
        let (min, max) = bounds_of(vertices.iter().map(|vertex| vertex.position));
        let positions = views.push(
            &mut bin,
            vertices
                .iter()
                .flat_map(|vertex| {
                    let p = vertex.position;
                    [p.x, p.y, p.z]
                })
                .flat_map(f32::to_le_bytes)
                .collect::<Vec<u8>>(),
            Some(ARRAY_BUFFER),
            12,
        );
        let normals = views.push(
            &mut bin,
            vertices
                .iter()
                .flat_map(|vertex| {
                    let n = vertex.normal;
                    [n.x, n.y, n.z]
                })
                .flat_map(f32::to_le_bytes)
                .collect::<Vec<u8>>(),
            Some(ARRAY_BUFFER),
            12,
        );
        let uvs = views.push(
            &mut bin,
            vertices
                .iter()
                .flat_map(|vertex| [vertex.uv.x, vertex.uv.y])
                .flat_map(f32::to_le_bytes)
                .collect::<Vec<u8>>(),
            Some(ARRAY_BUFFER),
            8,
        );
        let indices = views.push(
            &mut bin,
            submesh
                .indices
                .iter()
                .flat_map(|index| index.to_le_bytes())
                .collect::<Vec<u8>>(),
            Some(ELEMENT_ARRAY_BUFFER),
            4,
        );

        let count = vertices.len();
        let position_accessor = accessors.len();
        accessors.push(format!(
            "{{\"bufferView\":{positions},\"componentType\":{FLOAT},\"count\":{count},\
             \"type\":\"VEC3\",\"min\":[{},{},{}],\"max\":[{},{},{}]}}",
            number(min.x),
            number(min.y),
            number(min.z),
            number(max.x),
            number(max.y),
            number(max.z),
        ));
        let normal_accessor = accessors.len();
        accessors.push(format!(
            "{{\"bufferView\":{normals},\"componentType\":{FLOAT},\"count\":{count},\
             \"type\":\"VEC3\"}}"
        ));
        let uv_accessor = accessors.len();
        accessors.push(format!(
            "{{\"bufferView\":{uvs},\"componentType\":{FLOAT},\"count\":{count},\
             \"type\":\"VEC2\"}}"
        ));
        let index_accessor = accessors.len();
        accessors.push(format!(
            "{{\"bufferView\":{indices},\"componentType\":{UNSIGNED_INT},\"count\":{},\
             \"type\":\"SCALAR\"}}",
            submesh.indices.len()
        ));

        let material = submesh.material.min(model.materials.len().saturating_sub(1));
        let mesh = meshes.len();
        meshes.push(format!(
            "{{\"name\":{},\"primitives\":[{{\"attributes\":{{\"POSITION\":{position_accessor},\
             \"NORMAL\":{normal_accessor},\"TEXCOORD_0\":{uv_accessor}}},\
             \"indices\":{index_accessor},\"material\":{material}}}]}}",
            quoted(&submesh.name)
        ));
        nodes.push(format!(
            "{{\"name\":{},\"mesh\":{mesh}}}",
            quoted(&submesh.name)
        ));
    }

    if nodes.is_empty() {
        return Err(AssetError::invalid(
            &model.name,
            "lods[0]",
            "every submesh is empty, so there is nothing to write",
        ));
    }

    // Images before materials, because a material names a texture by index.
    let mut images: Vec<String> = Vec::with_capacity(model.textures.len());
    for texture in &model.textures {
        let png = encode_png(&model.name, texture)?;
        let view = views.push(&mut bin, png, None, 1);
        images.push(format!(
            "{{\"name\":{},\"bufferView\":{view},\"mimeType\":\"image/png\"}}",
            quoted(&texture.name)
        ));
    }

    let materials: Vec<String> = model
        .materials
        .iter()
        .map(|material| {
            let mut pbr = format!(
                "\"baseColorFactor\":[{},{},{},{}],\"metallicFactor\":{},\"roughnessFactor\":{}",
                number(material.base_color.x),
                number(material.base_color.y),
                number(material.base_color.z),
                number(material.base_color.w),
                number(material.metallic),
                number(material.roughness),
            );
            if let Some(texture) = material.base_color_texture {
                pbr.push_str(&format!(",\"baseColorTexture\":{{\"index\":{texture}}}"));
            }
            let mut extra = String::new();
            if let Some(texture) = material.orm_texture {
                extra.push_str(&format!(
                    ",\"metallicRoughnessTexture\":{{\"index\":{texture}}}"
                ));
            }
            let mut json = format!(
                "{{\"name\":{},\"pbrMetallicRoughness\":{{{pbr}{extra}}}",
                quoted(&material.name)
            );
            if let Some(texture) = material.normal_texture {
                json.push_str(&format!(
                    ",\"normalTexture\":{{\"index\":{texture},\"scale\":{}}}",
                    number(material.normal_scale)
                ));
            }
            if let Some(texture) = material.emissive_texture {
                json.push_str(&format!(",\"emissiveTexture\":{{\"index\":{texture}}}"));
            }
            if material.emissive != Vec3::ZERO {
                json.push_str(&format!(
                    ",\"emissiveFactor\":[{},{},{}]",
                    number(material.emissive.x),
                    number(material.emissive.y),
                    number(material.emissive.z),
                ));
            }
            match material.surface {
                SurfaceClass::Opaque => {}
                SurfaceClass::AlphaTest => json.push_str(&format!(
                    ",\"alphaMode\":\"MASK\",\"alphaCutoff\":{}",
                    number(material.alpha_cutoff)
                )),
                SurfaceClass::Transparent => json.push_str(",\"alphaMode\":\"BLEND\""),
            }
            // Two-sided is not a property this engine's materials carry; leaving it out means
            // glTF's default of back-face culling, which is what the renderer does.
            json.push('}');
            json
        })
        .collect();

    let textures: Vec<String> = (0..images.len())
        .map(|index| format!("{{\"sampler\":0,\"source\":{index}}}"))
        .collect();

    let mut json = String::with_capacity(4 * 1_024);
    json.push_str(
        "{\"asset\":{\"version\":\"2.0\",\"generator\":\"mygame procedural asset generator\"}",
    );
    json.push_str(&format!(
        ",\"scene\":0,\"scenes\":[{{\"name\":{},\"nodes\":[{}]}}]",
        quoted(&model.name),
        (0..nodes.len())
            .map(|index| index.to_string())
            .collect::<Vec<_>>()
            .join(",")
    ));
    json.push_str(&format!(",\"nodes\":[{}]", nodes.join(",")));
    json.push_str(&format!(",\"meshes\":[{}]", meshes.join(",")));
    json.push_str(&format!(",\"accessors\":[{}]", accessors.join(",")));
    json.push_str(&format!(",\"materials\":[{}]", materials.join(",")));
    if !images.is_empty() {
        json.push_str(&format!(",\"images\":[{}]", images.join(",")));
        json.push_str(&format!(",\"textures\":[{}]", textures.join(",")));
        // Repeat in both axes and trilinear-with-mipmaps, which is what every texture in this
        // project is sampled with. A sampler the file does not state is a sampler the loader
        // guesses.
        json.push_str(
            ",\"samplers\":[{\"magFilter\":9729,\"minFilter\":9987,\"wrapS\":10497,\
             \"wrapT\":10497}]",
        );
    }
    json.push_str(&format!(
        ",\"bufferViews\":[{}],\"buffers\":[{{\"byteLength\":{}}}]}}",
        views.json.join(","),
        bin.len()
    ));

    Ok(assemble(&json, &bin))
}

/// The buffer views written so far, and where each one starts.
#[derive(Debug, Default)]
struct Views {
    json: Vec<String>,
}

impl Views {
    /// Appends `bytes` to the binary chunk and records a view over them.
    ///
    /// `alignment` is the component size glTF requires the view to start on; padding to it
    /// here is what keeps a loader from having to copy an unaligned accessor out.
    fn push(
        &mut self,
        bin: &mut Vec<u8>,
        bytes: Vec<u8>,
        target: Option<u32>,
        alignment: usize,
    ) -> usize {
        let alignment = alignment.max(1);
        while bin.len() % alignment != 0 {
            bin.push(0);
        }
        let offset = bin.len();
        let length = bytes.len();
        bin.extend_from_slice(&bytes);
        let index = self.json.len();
        self.json.push(match target {
            Some(target) => format!(
                "{{\"buffer\":0,\"byteOffset\":{offset},\"byteLength\":{length},\
                 \"target\":{target}}}"
            ),
            None => format!(
                "{{\"buffer\":0,\"byteOffset\":{offset},\"byteLength\":{length}}}"
            ),
        });
        index
    }
}

/// Wraps a JSON document and a binary blob in the GLB container.
fn assemble(json: &str, bin: &[u8]) -> Vec<u8> {
    // Both chunks are padded to four bytes: the JSON one with spaces, which keep it valid
    // JSON, and the binary one with zeros.
    let mut json_bytes = json.as_bytes().to_vec();
    while json_bytes.len() % 4 != 0 {
        json_bytes.push(b' ');
    }
    let mut bin_bytes = bin.to_vec();
    while bin_bytes.len() % 4 != 0 {
        bin_bytes.push(0);
    }

    let total = 12 + 8 + json_bytes.len() + if bin_bytes.is_empty() { 0 } else { 8 + bin_bytes.len() };
    let mut out = Vec::with_capacity(total);
    out.extend_from_slice(&MAGIC.to_le_bytes());
    out.extend_from_slice(&2u32.to_le_bytes());
    out.extend_from_slice(&(total as u32).to_le_bytes());

    out.extend_from_slice(&(json_bytes.len() as u32).to_le_bytes());
    out.extend_from_slice(&CHUNK_JSON.to_le_bytes());
    out.extend_from_slice(&json_bytes);

    if !bin_bytes.is_empty() {
        out.extend_from_slice(&(bin_bytes.len() as u32).to_le_bytes());
        out.extend_from_slice(&CHUNK_BIN.to_le_bytes());
        out.extend_from_slice(&bin_bytes);
    }
    out
}

/// Encodes a texture as a PNG file.
///
/// Always RGBA8, whatever the runtime format says: PNG is a delivery container here and the
/// importer decodes it straight back to RGBA8. The colour space is carried by *which slot*
/// the texture is used in — a base colour map is sRGB and a normal map is not — exactly as it
/// is for an artist's export, and not by anything written into the file.
///
/// # Errors
///
/// [`AssetError::Malformed`] if the encoder refuses the texture, which means its dimensions
/// and its texel count disagree.
pub fn encode_png_file(texture: &TextureAsset) -> Result<Vec<u8>, AssetError> {
    encode_png(&texture.name, texture)
}

/// Encodes a texture as PNG, named after the model it belongs to for the error message.
fn encode_png(model: &str, texture: &TextureAsset) -> Result<Vec<u8>, AssetError> {
    let mut out = Vec::with_capacity(texture.texels.len() / 2);
    {
        let mut encoder = png::Encoder::new(&mut out, texture.width, texture.height);
        encoder.set_color(png::ColorType::Rgba);
        encoder.set_depth(png::BitDepth::Eight);
        let mut writer = encoder
            .write_header()
            .map_err(|error| png_error(model, texture, &error))?;
        let rgba: Vec<u8> = match texture.format {
            TextureFormat::Rgba8Unorm | TextureFormat::Rgba8Srgb => texture.texels.clone(),
        };
        writer
            .write_image_data(&rgba)
            .map_err(|error| png_error(model, texture, &error))?;
        writer
            .finish()
            .map_err(|error| png_error(model, texture, &error))?;
    }
    out.flush().ok();
    Ok(out)
}

/// A PNG encoder failure, named after the texture that caused it.
fn png_error(model: &str, texture: &TextureAsset, error: &png::EncodingError) -> AssetError {
    AssetError::Malformed {
        model: model.to_owned(),
        reason: format!("texture '{}' could not be encoded: {error}", texture.name),
    }
}

/// The lowest and highest corner of a set of positions.
fn bounds_of(positions: impl Iterator<Item = Vec3>) -> (Vec3, Vec3) {
    let mut min = Vec3::splat(f32::MAX);
    let mut max = Vec3::splat(f32::MIN);
    for position in positions {
        min = min.min(position);
        max = max.max(position);
    }
    (min, max)
}

/// A number as JSON, never in exponent form and never `NaN`.
///
/// `serde_json` would refuse a non-finite number and this writes one file per asset, so the
/// substitution is made here, loudly enough to see in the file: a coordinate that is not
/// finite is a bug in the generator, and writing a zero keeps the document loadable so the
/// rest of the model can be looked at.
fn number(value: f32) -> String {
    if !value.is_finite() {
        return "0".to_owned();
    }
    let text = format!("{value:.6}");
    let trimmed = text.trim_end_matches('0').trim_end_matches('.');
    if trimmed.is_empty() || trimmed == "-" {
        "0".to_owned()
    } else {
        trimmed.to_owned()
    }
}

/// A JSON string literal, with the five characters JSON cannot carry raw escaped.
fn quoted(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for character in text.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other if (other as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", other as u32)),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
#[allow(
    clippy::expect_used,
    reason = "test code may assert on known-good values"
)]
mod tests {
    use super::*;
    use crate::gltf_import::import_glb;
    use crate::material::MaterialAsset;
    use crate::mesh::{MeshVertex, SubMesh};
    use engine_core::math::{Vec2, Vec3};

    /// A unit quad lying in the XZ plane, with one texture on it.
    fn quad_model(name: &str) -> ModelAsset {
        let vertices = vec![
            MeshVertex::new(Vec3::new(-1.0, 0.0, -1.0), Vec3::Y, Vec2::new(0.0, 0.0)),
            MeshVertex::new(Vec3::new(1.0, 0.0, -1.0), Vec3::Y, Vec2::new(1.0, 0.0)),
            MeshVertex::new(Vec3::new(1.0, 0.0, 1.0), Vec3::Y, Vec2::new(1.0, 1.0)),
            MeshVertex::new(Vec3::new(-1.0, 0.0, 1.0), Vec3::Y, Vec2::new(0.0, 1.0)),
        ];
        let submesh = SubMesh::new(
            "quad",
            Geometry::Static(vertices),
            vec![0, 1, 2, 0, 2, 3],
            0,
        );
        let texture = TextureAsset::new(
            "test_map",
            2,
            2,
            TextureFormat::Rgba8Srgb,
            vec![
                255, 0, 0, 255, 0, 255, 0, 255, 0, 0, 255, 255, 255, 255, 255, 255,
            ],
        )
        .expect("a 2x2 texture");
        let material = MaterialAsset::colored("test_material", 0.5, 0.6, 0.7)
            .with_roughness(0.25)
            .with_metallic(0.75)
            .with_base_color_texture(0);
        ModelAsset::rigid(name, vec![submesh], vec![material], vec![texture])
    }

    #[test]
    fn a_model_survives_being_written_and_read_back() {
        let original = quad_model("round_trip");
        let bytes = export_glb(&original).expect("the model exports");
        let restored = import_glb("round_trip", &bytes).expect("the export imports");

        let source = original.lod0().expect("geometry").submeshes[0].clone();
        let target = restored.lod0().expect("geometry").submeshes[0].clone();
        assert_eq!(target.indices, source.indices);
        let (Geometry::Static(before), Geometry::Static(after)) = (&source.geometry, &target.geometry)
        else {
            panic!("both are static geometry");
        };
        assert_eq!(after.len(), before.len());
        for (index, (before, after)) in before.iter().zip(after).enumerate() {
            assert!(
                (after.position - before.position).length() < 1e-5,
                "vertex {index} moved"
            );
            assert!((after.normal - before.normal).length() < 1e-5, "normal {index}");
            assert!((after.uv - before.uv).length() < 1e-5, "uv {index}");
        }
    }

    #[test]
    fn a_materials_numbers_and_its_texture_survive_the_round_trip() {
        let original = quad_model("materials");
        let bytes = export_glb(&original).expect("the model exports");
        let restored = import_glb("materials", &bytes).expect("the export imports");

        let material = &restored.materials[0];
        assert!((material.roughness - 0.25).abs() < 1e-6);
        assert!((material.metallic - 0.75).abs() < 1e-6);
        assert_eq!(material.base_color_texture, Some(0));

        let texture = &restored.textures[0];
        assert_eq!((texture.width, texture.height), (2, 2));
        assert_eq!(
            texture.texels, original.textures[0].texels,
            "PNG is lossless, so every texel comes back"
        );
    }

    #[test]
    fn the_container_is_a_valid_glb_header() {
        let bytes = export_glb(&quad_model("header")).expect("the model exports");
        assert_eq!(&bytes[0..4], b"glTF");
        assert_eq!(u32::from_le_bytes([bytes[4], bytes[5], bytes[6], bytes[7]]), 2);
        assert_eq!(
            u32::from_le_bytes([bytes[8], bytes[9], bytes[10], bytes[11]]) as usize,
            bytes.len(),
            "the header's length is the file's length"
        );
        assert_eq!(bytes.len() % 4, 0, "every chunk is padded to four bytes");
    }

    #[test]
    fn a_model_with_no_geometry_is_refused_rather_than_written_empty() {
        let empty = ModelAsset::rigid("empty", Vec::new(), Vec::new(), Vec::new());
        assert!(export_glb(&empty).is_err());
    }
}
