//! The balance report: the matrix as markdown.
//!
//! ```text
//! 1. Summary matrix        class x build  by  gear profile, single-target and AoE-8 DPS
//! 2. Balance check         Mage DPS against the other two classes, per gear profile
//! 3. Class detail          the default build at each gear tier: breakdown, resources,
//!                          cooldowns, buff and debuff uptime
//! 4. Rotations             the priority list each AI plays
//! 5. Gear profiles         what each profile is and how it was derived
//! 6. Talent validation     is any talent mandatory or worthless (`validation.rs`)
//! 7. Gear scaling          does each gear tier beat the one below it (`scaling.rs`)
//! ```

use std::fmt::Write as _;

use engine_game::ability::AbilityId;
use engine_game::firemage::FireAbility;
use engine_game::status::StatusKind;

use crate::Options;
use crate::build::ClassBuild;
use crate::class::Class;
use crate::gear::{GearProfile, GearTier, PROFILES};
use crate::matrix::{AOE3, AOE8, Cell, Matrix, SCENARIOS, ST60, ST180, TARGET_HEALTH};
use crate::metrics::{AURA_COUNT, Metrics, aura_name};
use crate::scaling::{self, Scaling};
use crate::validation::{self, Validation};

/// Auras below this uptime are left out of a detail table.
const MIN_UPTIME: f64 = 0.005;

/// The whole report.
#[must_use]
pub fn matrix_report(
    matrix: &Matrix,
    options: &Options,
    validation: Option<&Validation>,
    scaling: Option<&Scaling>,
) -> String {
    let mut out = String::with_capacity(96 * 1024);
    header(&mut out, matrix, options);
    summary(&mut out, matrix);
    balance_check(&mut out, matrix);
    detail(&mut out, matrix);
    rotations(&mut out, matrix);
    gear_profiles(&mut out);
    if let Some(validation) = validation {
        validation::write_section(&mut out, validation);
    }
    if let Some(scaling) = scaling {
        scaling::write_section(&mut out, scaling);
    }
    caveats(&mut out);
    out
}

/// Single-target 60 s DPS of a cell, or NaN-free zero if it was not run.
fn dps(matrix: &Matrix, class: Class, build: &str, variant: &str, scenario: usize) -> Option<f64> {
    matrix
        .find(class, build, variant, scenario)
        .map(|cell| cell.result.dps)
}

fn header(out: &mut String, matrix: &Matrix, options: &Options) {
    let _ = writeln!(out, "# Balance simulator report\n");
    let _ = writeln!(
        out,
        "Generated by `engine-sim`. Every number comes from the game's own `Simulation`: the \
         real ability table, cooldowns, damage function and stat pipeline, driven headless by \
         one rotation AI per class. A run is deterministic: the same seed and iteration count \
         reproduce this file byte for byte.\n"
    );
    let _ = writeln!(
        out,
        "* Seed `{}`, {} iterations per cell, {} cells.",
        options.seed,
        options.iterations,
        matrix.cells.len()
    );
    let _ = writeln!(
        out,
        "* Targets are passive dummies with {TARGET_HEALTH:.0} health each, so nothing dies and \
         DPS is sustained output. They wander a few metres every two seconds, as in the \
         FireMage study, so cones, lines and melee reach are tested."
    );
    let _ = writeln!(out, "* Scenarios:");
    for scenario in SCENARIOS {
        let _ = writeln!(
            out,
            "  * **{}** - `{}`: {} target(s), {:.0} s.",
            scenario.label, scenario.id, scenario.targets, scenario.duration
        );
    }
    let _ = writeln!(out);
}

// ------------------------------------------------------------------ 1. summary

fn summary(out: &mut String, matrix: &Matrix) {
    let profiles = matrix.profiles();
    let _ = writeln!(out, "## 1. Summary matrix\n");
    for (title, first, second) in [
        ("Single target 60 s DPS / AoE 8 targets DPS", ST60, AOE8),
        ("Single target 180 s DPS / AoE 3 targets DPS", ST180, AOE3),
    ] {
        let _ = writeln!(out, "**{title}**\n");
        let _ = write!(out, "| Class / build |");
        for profile in &profiles {
            let _ = write!(out, " {} |", profile.label());
        }
        let _ = writeln!(out);
        let _ = write!(out, "|---|");
        for _ in &profiles {
            let _ = write!(out, "---:|");
        }
        let _ = writeln!(out);
        for class in Class::ALL {
            for build in matrix.builds(class) {
                let _ = write!(out, "| {} / {} |", class.title(), build.name());
                for profile in &profiles {
                    let a = dps(matrix, class, build.name(), profile.variant, first);
                    let b = dps(matrix, class, build.name(), profile.variant, second);
                    match a.zip(b) {
                        Some((a, b)) => {
                            let _ = write!(out, " {a:.0} / {b:.0} |");
                        }
                        None => {
                            let _ = write!(out, " - |");
                        }
                    }
                }
                let _ = writeln!(out);
            }
        }
        let _ = writeln!(out);
    }
}

// ------------------------------------------------------------------ 2. balance

/// The Mage's best build at a profile and scenario, by DPS.
fn best_mage(matrix: &Matrix, variant: &str, scenario: usize) -> Option<(String, f64)> {
    matrix
        .builds(Class::Mage)
        .iter()
        .filter_map(|build| {
            dps(matrix, Class::Mage, build.name(), variant, scenario)
                .map(|dps| (build.name().to_owned(), dps))
        })
        .max_by(|a, b| a.1.partial_cmp(&b.1).unwrap_or(std::cmp::Ordering::Equal))
}

fn balance_check(out: &mut String, matrix: &Matrix) {
    let _ = writeln!(out, "## 2. Balance check\n");
    let present = |class: Class| !matrix.builds(class).is_empty();
    if !Class::ALL.iter().all(|class| present(*class)) {
        let _ = writeln!(
            out,
            "Skipped: the balance check compares all three classes, and this run covers only \
             some of them.\n"
        );
        return;
    }
    let _ = writeln!(
        out,
        "**Ratio = Mage DPS / (Warrior DPS + Druid DPS)**, target about 1.00: the design asks \
         for the Mage to deal roughly what the other two deal together. The Mage is shown with its `Default` \
         build (no talents) and with the best of its builds.\n"
    );
    for (scenario_index, title) in [
        (ST60, "Single target, 60 s"),
        (AOE8, "AoE, 8 targets, 60 s"),
    ] {
        let _ = writeln!(out, "**{title}**\n");
        let _ = writeln!(
            out,
            "| Gear | Warrior | Druid | Mage Default | Mage best (build) | Mage Default / (W+D) | Mage best / (W+D) |"
        );
        let _ = writeln!(out, "|---|---:|---:|---:|---:|---:|---:|");
        for profile in matrix.profiles() {
            let variant = profile.variant;
            let warrior = dps(matrix, Class::Warrior, "Default", variant, scenario_index);
            let druid = dps(matrix, Class::Druid, "Default", variant, scenario_index);
            let default = dps(matrix, Class::Mage, "Default", variant, scenario_index);
            let best = best_mage(matrix, variant, scenario_index);
            let (Some(warrior), Some(druid), Some(default), Some((best_name, best))) =
                (warrior, druid, default, best)
            else {
                continue;
            };
            let sum = warrior + druid;
            let _ = writeln!(
                out,
                "| {} | {warrior:.0} | {druid:.0} | {default:.0} | {best:.0} ({best_name}) | **{:.2}** | **{:.2}** |",
                profile.label(),
                ratio(default, sum),
                ratio(best, sum),
            );
        }
        let _ = writeln!(out);
    }
}

fn ratio(a: f64, b: f64) -> f64 {
    if b > 0.0 { a / b } else { 0.0 }
}

// ------------------------------------------------------------------ 3. detail

fn detail(out: &mut String, matrix: &Matrix) {
    let _ = writeln!(out, "## 3. Class detail\n");
    let _ = writeln!(
        out,
        "The `Default` build of each class at each gear tier (the balanced set for medium), \
         single target for 60 s. Eight-target breakdowns follow for top gear.\n"
    );
    for class in Class::ALL {
        let Some(build) = matrix.builds(class).into_iter().next() else {
            continue;
        };
        let _ = writeln!(out, "### {}\n", class.title());
        for tier in GearTier::ALL {
            let profile = GearProfile::headline(tier);
            let Some(cell) = matrix.find(class, build.name(), profile.variant, ST60) else {
                continue;
            };
            let _ = writeln!(
                out,
                "#### {} - {} gear\n\n{}\n",
                class.title(),
                profile.label(),
                profile.describe(class.hero())
            );
            cell_detail(out, cell, class);
            if tier == GearTier::High
                && let Some(aoe) = matrix.find(class, build.name(), profile.variant, AOE8)
            {
                let _ = writeln!(
                    out,
                    "**{} - {} gear - {}**: {:.0} DPS\n",
                    class.title(),
                    profile.label(),
                    SCENARIOS[AOE8].label,
                    aoe.result.dps
                );
                breakdown(
                    out,
                    &aoe.result.by_ability,
                    &aoe.result.metrics,
                    aoe.result.damage,
                );
            }
        }
    }
}

fn cell_detail(out: &mut String, cell: &Cell, class: Class) {
    let result = &cell.result;
    let metrics = &result.metrics;
    let _ = writeln!(
        out,
        "**{} DPS** ({:.0} total damage over {:.0} s)\n",
        format_args!("{:.0}", result.dps),
        result.damage,
        result.seconds
    );
    breakdown(out, &result.by_ability, metrics, result.damage);
    resources(out, metrics, class, result);
    cooldowns(out, cell, metrics);
    auras(out, "Buffs (on the player)", metrics, false);
    auras(out, "Debuffs (on the targets)", metrics, true);
}

/// Every ability in the table, by slot, with its name.
fn abilities() -> impl Iterator<Item = FireAbility> {
    FireAbility::ALL.into_iter()
}

fn breakdown(
    out: &mut String,
    by_ability: &[f64; engine_game::ability::ABILITY_SLOTS],
    metrics: &Metrics,
    total: f64,
) {
    let mut rows: Vec<(FireAbility, f64, f64)> = abilities()
        .filter_map(|ability| {
            let slot = AbilityId::from_fire(ability).slot();
            let damage = by_ability[slot];
            (damage > 0.0 || metrics.casts[slot] >= 0.5).then_some((
                ability,
                damage,
                metrics.casts[slot],
            ))
        })
        .collect();
    rows.sort_by(|a, b| b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal));
    let _ = writeln!(out, "| Ability | Casts | Damage | % of total |");
    let _ = writeln!(out, "|---|---:|---:|---:|");
    for (ability, damage, casts) in rows {
        let _ = writeln!(
            out,
            "| {} | {:.1} | {:.0} | {:.1}% |",
            title_case(ability.definition().name),
            casts,
            damage,
            ratio(damage, total) * 100.0
        );
    }
    let _ = writeln!(out);
}

fn resources(
    out: &mut String,
    metrics: &Metrics,
    class: Class,
    result: &crate::scenario::RunResult,
) {
    let r = &metrics.resources;
    let _ = writeln!(out, "Resources:\n");
    match class {
        Class::Mage => {
            let counters = &result.counters;
            let _ = writeln!(
                out,
                "* Heat: {:.0} generated (casts x each row's Heat, before modifiers), average \
                 {:.1}, {} full-bar cycles; {:.1} s at 30+, {:.1} s at 70+, {:.1} s Inferno. \
                 Heat is not spent; it decays.",
                r.heat_generated,
                counters.average_heat(),
                counters.heat_cycles,
                counters.seconds_warm,
                counters.seconds_hot,
                counters.seconds_inferno
            );
            let _ = writeln!(
                out,
                "* Ignite: {} stack applications, {:.2} average stacks on a burning target, {} \
                 detonations.",
                counters.ignite_applications,
                counters.average_ignite_stacks(),
                counters.detonations
            );
        }
        Class::Druid => {
            let _ = writeln!(
                out,
                "* Mana: {:.0} spent, {:.0} restored by Wrath (regeneration not counted).",
                r.mana_spent, r.mana_restored
            );
            let _ = writeln!(
                out,
                "* Astral Power: {:.0} generated, {:.0} spent on empowerments ({:.1} empowered casts).",
                r.astral_generated, r.astral_spent, r.empowerments
            );
        }
        Class::Warrior => {
            let fervor = StatusKind::BattleFervor.index();
            let _ = writeln!(
                out,
                "* Valor: {:.1} generated (+1 per War Stomp, Colossus Strike or Shield Charge \
                 that lands, and Bloodied Valor's final bleed tick), {:.1} bar fills. Block, \
                 Parry and Dodge pay none, and the dummies never attack anyway.",
                r.valor_generated, r.valor_fills
            );
            let _ = writeln!(
                out,
                "* Battle Fervor: {:.1} stacks gained, {:.1}% uptime at {:.2} average stacks \
                 while up. Survival proxy (average share of a physical hit not taken): {:.1}%.",
                r.fervor_stacks_gained,
                metrics.buff_uptime(fervor) * 100.0,
                metrics.buffs[fervor].average_stacks(),
                metrics.average_mitigation() * 100.0
            );
        }
    }
    let _ = writeln!(out);
}

fn cooldowns(out: &mut String, cell: &Cell, metrics: &Metrics) {
    let rotation = cell.build.rotation();
    let tracked = rotation.tracked_cooldowns();
    if tracked.is_empty() {
        let _ = writeln!(
            out,
            "Cooldowns: this rotation has no damage ability on a cooldown (see resources).\n"
        );
        return;
    }
    let _ = writeln!(
        out,
        "| Cooldown | Cooldown (s) | Casts | Max casts | Used | Idle-ready (s) |"
    );
    let _ = writeln!(out, "|---|---:|---:|---:|---:|---:|");
    for ability in tracked {
        let slot = AbilityId::from_fire(*ability).slot();
        let _ = writeln!(
            out,
            "| {} | {:.0} | {:.1} | {:.1} | {:.0}% | {:.1} |",
            title_case(ability.definition().name),
            ability.definition().cooldown,
            metrics.casts[slot],
            metrics.max_casts[slot],
            metrics.cooldown_efficiency(*ability) * 100.0,
            metrics.ready_seconds[slot]
        );
    }
    let _ = writeln!(
        out,
        "\n*Max casts* is the charges the ability starts with plus what its cooldown allows \
         in the fight, at the haste in force each tick. *Idle-ready* is the time at least one \
         charge was available but not yet spent.\n"
    );
}

fn auras(out: &mut String, title: &str, metrics: &Metrics, debuff: bool) {
    let mut rows: Vec<(usize, f64, f64)> = (0..AURA_COUNT)
        .filter_map(|aura| {
            let (uptime, stacks) = if debuff {
                (
                    metrics.debuff_uptime(aura),
                    metrics.debuffs[aura].average_stacks(),
                )
            } else {
                (
                    metrics.buff_uptime(aura),
                    metrics.buffs[aura].average_stacks(),
                )
            };
            (uptime >= MIN_UPTIME).then_some((aura, uptime, stacks))
        })
        .collect();
    if rows.is_empty() {
        let _ = writeln!(out, "{title}: none.\n");
        return;
    }
    rows.sort_by(|a, b| b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal));
    let _ = writeln!(out, "| {title} | Uptime | Average stacks |");
    let _ = writeln!(out, "|---|---:|---:|");
    for (aura, uptime, stacks) in rows {
        let _ = writeln!(
            out,
            "| {} | {:.1}% | {:.2} |",
            aura_name(aura),
            uptime * 100.0,
            stacks
        );
    }
    let _ = writeln!(out);
}

/// `FLAME LANCE` -> `Flame Lance`.
fn title_case(text: &str) -> String {
    text.split(' ')
        .map(|word| {
            let mut chars = word.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_uppercase().collect::<String>() + &chars.as_str().to_lowercase()
            })
        })
        .collect::<Vec<_>>()
        .join(" ")
}

// ------------------------------------------------------------------ 4. rotations

fn rotations(out: &mut String, matrix: &Matrix) {
    let _ = writeln!(out, "## 4. Rotations\n");
    let _ = writeln!(
        out,
        "Each AI is a priority list over ability presses and cooldown readiness; it takes at \
         most one action per tick and none during a cast or the global cooldown. The lists \
         below are printed from the code that implements them. They answer, per class: what to \
         cast, when to use cooldowns, and which buffs and debuffs to keep up.\n"
    );
    let mut seen: Vec<&'static str> = Vec::new();
    for class in Class::ALL {
        for build in matrix.builds(class) {
            let rotation = build.rotation();
            if seen.contains(&rotation.name()) {
                continue;
            }
            seen.push(rotation.name());
            let _ = writeln!(out, "### {}\n", rotation.name());
            if let ClassBuild::Mage(mage) = &build {
                let _ = writeln!(
                    out,
                    "Played by: {} ({}). Talents: {}.\n",
                    build.name(),
                    mage.label(),
                    build.talent_names()
                );
            }
            for (index, line) in rotation.priority().iter().enumerate() {
                let _ = writeln!(out, "{}. {line}", index + 1);
            }
            let _ = writeln!(out);
        }
    }
    let _ = writeln!(
        out,
        "**Cooldowns**: every damaging cooldown is pressed the moment it is ready. The Warrior \
         has no offensive cooldown beyond its damage abilities (Last Stand and Shield Block are \
         pressed on cooldown only by builds whose talents make them matter); the Druid has none at all (its \
         Astral Power button is a resource, not a timer); the Mage's only burst cooldown is \
         Fire Mastery.\n"
    );
    let _ = writeln!(
        out,
        "**Buffs and debuffs maintained**: Mage - Ignite on the primary target, the Fire \
         Mastery window, Heat in the Inferno State. Warrior - Sundered (War Stomp), Bleeding \
         (Colossus Strike), Recuperating. Druid - Moonfire and Sunfire on the target(s), \
         Nature's Exposure from Wrath, and every empowerment spent.\n"
    );
}

// ------------------------------------------------------------------ 5. gear

fn gear_profiles(out: &mut String) {
    let _ = writeln!(out, "## 5. Gear profiles\n");
    let _ = writeln!(
        out,
        "Gear is real: each profile names items from `assets/catalog/loot.json` (best in slot \
         for the hero's main stat, chosen deterministically) and the quality and sharpening \
         they are worn at. The simulator builds the character sheet with the realm's own \
         `sheet_of` and lets the game compute the stats (`gear_stats`, the rating curve \
         `x / (x + 100)`, the main-stat bridge), exactly as a realm fight does. `low` wears the \
         best rare in every slot; `medium` an epic in every other slot and rares between; \
         `high` the best epic in each slot that has one (the catalog has epics for head, chest, \
         necklace, one ring and the trinkets, so the rest are rares); `p2_max` the same pieces \
         at the quality ceiling with a heavy sharpening. `--gear top` is an alias of `high`.\n"
    );
    let _ = writeln!(
        out,
        "| Profile | Quality | Sharpening | Warrior | Mage / Druid |"
    );
    let _ = writeln!(out, "|---|---:|---:|---|---|");
    for profile in PROFILES {
        let _ = writeln!(
            out,
            "| {} | {} | +{} | {} | {} |",
            profile.label(),
            profile.quality,
            profile.sharpening,
            profile.describe(Class::Warrior.hero()),
            profile.describe(Class::Mage.hero()),
        );
    }
    let _ = writeln!(out);
}

fn caveats(out: &mut String) {
    let _ = writeln!(out, "## Caveats\n");
    let _ = writeln!(
        out,
        "* These are *damage* rotations. The Warrior is a tank and the Druid a healer; their \
         defensive and healing kits are not exercised: the dummies never attack, so Block, \
         Parry and Dodge never fire, and the Warrior's Valor comes only from its own casts.\n\
         * Gear is whatever the catalog's pieces grant, so Versatility, Spirit, Stamina and Armor ride along with the main stat, Haste and Critical Strike; Versatility and Spirit are not chosen for.\n\
         * Every class has `Default` (no talents), `Build A` and `Build B`, which buy \
         talents from `assets/catalog/talents.json` within the 20-point budget.\n\
         * Colossus Strike's bleed lands on at most three targets (the selected one, then \
         the nearest): that cap is what keeps the Warrior's AoE 8 DPS level with the Mage's. \
         Its direct hit still cleaves everything in reach.\n\
         * Targets wander on a seeded timer, so area abilities lose some hits and the \
         Warrior spends some time walking; this is part of the number, not noise.\n\
         * Cooldown *max casts* ignores cooldown-reduction effects, so an ability that is \
         reset by another can exceed 100%.
\
         * The Mage starts every fight with a full Ultimate bar and uses Moving Fire Beam at \
         the pull. The bar refills in about ninety seconds, level with the beam's own \
         ninety-second cooldown, so a sixty-second window holds one beam where a long fight \
         holds one every ninety seconds: the 60 s Mage figures overstate the sustained \
         contribution by about half."
    );
}
