//! What a fight is measured by, beyond total damage.
//!
//! A [`Recorder`] watches a [`Simulation`] tick by tick - it never touches it - and builds a
//! [`Metrics`]: casts, resource flow, cooldown usage and aura uptime. Everything is read from
//! the game's own state (the damage meter, the event stream, the status sets, the cooldown
//! book), so a number here is a number the game computed.
//!
//! # Auras
//!
//! An *aura* is anything with an on/off state and possibly stacks: every
//! [`StatusKind`] the game has, plus three FireMage states that are not statuses (Ignite on a
//! target, the Inferno State, the Fire Mastery window). Auras on the **player** are buffs;
//! auras on the **targets** are debuffs. Uptime is the fraction of the time the aura was
//! active, and average stacks is stack-seconds over active seconds, so a buff that is up for
//! ten per cent of the fight at five stacks reads 10% and 5.0.
//!
//! For a pack, a debuff's uptime is averaged over target-seconds: eight targets that each
//! carry it half the time read 50%, not "up whenever any target has it".

use engine_game::ability::{ABILITY_SLOTS, AbilityId};
use engine_game::event::CombatEvent;
use engine_game::firemage::FireAbility;
use engine_game::hero::Hero;
use engine_game::sim::Simulation;
use engine_game::status::{STATUS_KIND_COUNT, StatusKind};

/// Auras beyond the statuses: Ignite on a target.
pub const AURA_IGNITE: usize = STATUS_KIND_COUNT;
/// The Inferno State, on the player.
pub const AURA_INFERNO: usize = STATUS_KIND_COUNT + 1;
/// The Fire Mastery window, on the player.
pub const AURA_MASTERY: usize = STATUS_KIND_COUNT + 2;
/// How many auras there are.
pub const AURA_COUNT: usize = STATUS_KIND_COUNT + 3;

/// The display name of aura `index`.
#[must_use]
pub fn aura_name(index: usize) -> &'static str {
    match index {
        AURA_IGNITE => "Ignite",
        AURA_INFERNO => "Inferno State",
        AURA_MASTERY => "Fire Mastery",
        other => StatusKind::ALL
            .get(other)
            .map_or("?", |kind| kind.display_name()),
    }
}

/// Seconds an aura was active and stack-seconds accumulated while it was.
#[derive(Debug, Default, Clone, Copy, PartialEq)]
pub struct AuraTrack {
    /// Seconds (or target-seconds) it was active.
    pub active: f64,
    /// Stacks integrated over those seconds.
    pub stack_seconds: f64,
}

impl AuraTrack {
    /// Average stacks while active, zero if it never was.
    #[must_use]
    pub fn average_stacks(&self) -> f64 {
        if self.active > 0.0 {
            self.stack_seconds / self.active
        } else {
            0.0
        }
    }
}

/// How much of each class resource moved.
#[derive(Debug, Default, Clone, Copy, PartialEq)]
pub struct ResourceUse {
    /// Mana paid for casts (Druid).
    pub mana_spent: f64,
    /// Mana given back by abilities rather than regeneration (Druid).
    pub mana_restored: f64,
    /// Astral Power generated by casts (Druid).
    pub astral_generated: f64,
    /// Astral Power spent on empowerments (Druid).
    pub astral_spent: f64,
    /// How many empowerments that bought (Druid): the cost differs with Astral Attunement.
    pub empowerments: f64,
    /// Heat the casts generated at their rows' nominal values (FireMage).
    pub heat_generated: f64,
}

/// Everything measured about one fight, or the sum or average of several.
#[derive(Debug, Clone, PartialEq)]
pub struct Metrics {
    /// Seconds simulated.
    pub seconds: f64,
    /// Target-seconds: each living target for each second it lived.
    pub target_seconds: f64,
    /// Casts by ability slot.
    pub casts: [f64; ABILITY_SLOTS],
    /// Seconds a charge sat ready, by ability slot (cooldown abilities only).
    pub ready_seconds: [f64; ABILITY_SLOTS],
    /// Casts the cooldown would have allowed, by ability slot (cooldown abilities only).
    pub max_casts: [f64; ABILITY_SLOTS],
    /// Auras on the player.
    pub buffs: [AuraTrack; AURA_COUNT],
    /// Auras on the targets.
    pub debuffs: [AuraTrack; AURA_COUNT],
    /// Resource flow.
    pub resources: ResourceUse,
}

impl Default for Metrics {
    fn default() -> Self {
        Self {
            seconds: 0.0,
            target_seconds: 0.0,
            casts: [0.0; ABILITY_SLOTS],
            ready_seconds: [0.0; ABILITY_SLOTS],
            max_casts: [0.0; ABILITY_SLOTS],
            buffs: [AuraTrack::default(); AURA_COUNT],
            debuffs: [AuraTrack::default(); AURA_COUNT],
            resources: ResourceUse::default(),
        }
    }
}

impl Metrics {
    /// Applies `f` to every number, pairing it with the same number of `other`.
    fn zip_with(&mut self, other: &Metrics, f: impl Fn(f64, f64) -> f64) {
        self.seconds = f(self.seconds, other.seconds);
        self.target_seconds = f(self.target_seconds, other.target_seconds);
        for slot in 0..ABILITY_SLOTS {
            self.casts[slot] = f(self.casts[slot], other.casts[slot]);
            self.ready_seconds[slot] = f(self.ready_seconds[slot], other.ready_seconds[slot]);
            self.max_casts[slot] = f(self.max_casts[slot], other.max_casts[slot]);
        }
        for aura in 0..AURA_COUNT {
            for (mine, theirs) in [
                (&mut self.buffs[aura], &other.buffs[aura]),
                (&mut self.debuffs[aura], &other.debuffs[aura]),
            ] {
                mine.active = f(mine.active, theirs.active);
                mine.stack_seconds = f(mine.stack_seconds, theirs.stack_seconds);
            }
        }
        let (mine, theirs) = (&mut self.resources, &other.resources);
        mine.mana_spent = f(mine.mana_spent, theirs.mana_spent);
        mine.mana_restored = f(mine.mana_restored, theirs.mana_restored);
        mine.astral_generated = f(mine.astral_generated, theirs.astral_generated);
        mine.astral_spent = f(mine.astral_spent, theirs.astral_spent);
        mine.empowerments = f(mine.empowerments, theirs.empowerments);
        mine.heat_generated = f(mine.heat_generated, theirs.heat_generated);
    }

    /// Adds another run in.
    pub fn accumulate(&mut self, other: &Metrics) {
        self.zip_with(other, |a, b| a + b);
    }

    /// Divides every total by `runs`.
    #[must_use]
    pub fn averaged(&self, runs: u32) -> Metrics {
        let divisor = f64::from(runs.max(1));
        let mut result = self.clone();
        result.zip_with(self, |a, _| a / divisor);
        result
    }

    /// Fraction of the fight the player had `aura`, in `0.0..=1.0`.
    #[must_use]
    pub fn buff_uptime(&self, aura: usize) -> f64 {
        ratio(self.buffs[aura].active, self.seconds)
    }

    /// Fraction of target-time the targets had `aura`, in `0.0..=1.0`.
    #[must_use]
    pub fn debuff_uptime(&self, aura: usize) -> f64 {
        ratio(self.debuffs[aura].active, self.target_seconds)
    }

    /// Casts per ability slot as a fraction of what its cooldown allowed.
    #[must_use]
    pub fn cooldown_efficiency(&self, ability: FireAbility) -> f64 {
        let slot = AbilityId::from_fire(ability).slot();
        ratio(self.casts[slot], self.max_casts[slot])
    }
}

/// `part / whole`, clamped into `0.0..=1.0` and zero over zero.
fn ratio(part: f64, whole: f64) -> f64 {
    if whole <= 0.0 {
        0.0
    } else {
        (part / whole).clamp(0.0, 1.0)
    }
}

/// Watches a simulation and fills in a [`Metrics`].
pub struct Recorder {
    metrics: Metrics,
    cooldown_abilities: Vec<FireAbility>,
    started: bool,
}

impl Recorder {
    /// A recorder for a hero: every ability of theirs with a cooldown is tracked.
    #[must_use]
    pub fn new(hero: Hero) -> Self {
        let cooldown_abilities = hero
            .abilities()
            .iter()
            .copied()
            .filter(|ability| ability.definition().cooldown > 0.0)
            .collect();
        Self {
            metrics: Metrics::default(),
            cooldown_abilities,
            started: false,
        }
    }

    /// Looks at the simulation after one step of `step` seconds.
    pub fn observe(&mut self, simulation: &Simulation, targets: &[engine_game::entity::EntityId]) {
        let step = f64::from(simulation.timestep().step_seconds());
        let player = simulation.player().entity;
        let metrics = &mut self.metrics;
        metrics.seconds += step;

        // Cooldowns. The theoretical maximum is the charges the ability starts with plus the
        // progress its cooldown made, at the haste in force this tick.
        let mage = simulation.mage();
        let haste = f64::from(mage.haste());
        let effects = mage.effects();
        for ability in &self.cooldown_abilities {
            let slot = AbilityId::from_fire(*ability).slot();
            let definition = ability.definition();
            if !self.started {
                metrics.max_casts[slot] = f64::from(definition.charges_with(effects));
            }
            let cooldown = f64::from(definition.cooldown_with(effects));
            let speed = if definition.cooldown_hasted {
                1.0 + haste
            } else {
                1.0
            };
            if cooldown > 0.0 {
                metrics.max_casts[slot] += step * speed / cooldown;
            }
            if mage.abilities.is_ready(*ability) {
                metrics.ready_seconds[slot] += step;
            }
        }
        self.started = true;

        // Buffs on the player.
        if let Some(statuses) = simulation.world().statuses(player) {
            for status in statuses.iter() {
                let track = &mut metrics.buffs[status.kind.index()];
                track.active += step;
                track.stack_seconds += step * f64::from(status.stacks);
            }
        }
        if simulation.hero() == Hero::FireMage {
            if mage.heat.is_inferno() {
                metrics.buffs[AURA_INFERNO].active += step;
                metrics.buffs[AURA_INFERNO].stack_seconds += step;
            }
            if mage.mastery_buff.is_active() {
                metrics.buffs[AURA_MASTERY].active += step;
                metrics.buffs[AURA_MASTERY].stack_seconds += step;
            }
        }

        // Debuffs on every living target.
        for target in targets {
            if !simulation.world().is_alive(*target) {
                continue;
            }
            metrics.target_seconds += step;
            if let Some(statuses) = simulation.world().statuses(*target) {
                for status in statuses.iter() {
                    let track = &mut metrics.debuffs[status.kind.index()];
                    track.active += step;
                    track.stack_seconds += step * f64::from(status.stacks);
                }
            }
            if simulation.hero() == Hero::FireMage {
                let stacks = mage.ignite.stacks(*target);
                if stacks > 0 {
                    let track = &mut metrics.debuffs[AURA_IGNITE];
                    track.active += step;
                    track.stack_seconds += step * f64::from(stacks);
                }
            }
        }

        self.observe_events(simulation);
    }

    /// Reads the resource events the simulation currently holds.
    ///
    /// Called twice per tick: once after the rotation has pressed its button and once after the
    /// step. An instant cast lands, and announces its Mana and Astral Power, *before* the step
    /// that clears the stream, so reading only after the step would miss every instant spell.
    pub fn observe_events(&mut self, simulation: &Simulation) {
        let player = simulation.player().entity;
        let metrics = &mut self.metrics;
        for event in simulation.events() {
            match *event {
                CombatEvent::ManaSpent { entity, amount, .. } if entity == player => {
                    metrics.resources.mana_spent += f64::from(amount);
                }
                CombatEvent::ManaRestored { entity, amount, .. } if entity == player => {
                    metrics.resources.mana_restored += f64::from(amount);
                }
                CombatEvent::AstralPowerGained { entity, amount, .. } if entity == player => {
                    metrics.resources.astral_generated += f64::from(amount);
                }
                CombatEvent::AstralPowerSpent { entity, amount, .. } if entity == player => {
                    metrics.resources.astral_spent += f64::from(amount);
                    metrics.resources.empowerments += 1.0;
                }
                _ => {}
            }
        }
    }

    /// Finishes the recording, folding in what only the damage meter knows.
    #[must_use]
    pub fn finish(mut self, simulation: &Simulation) -> Metrics {
        let meter = simulation.meter();
        for (slot, totals) in meter.abilities().iter().enumerate() {
            self.metrics.casts[slot] = f64::from(totals.casts);
        }
        if simulation.hero() == Hero::FireMage {
            self.metrics.resources.heat_generated = simulation
                .hero()
                .abilities()
                .iter()
                .map(|ability| {
                    let slot = AbilityId::from_fire(*ability).slot();
                    f64::from(ability.definition().fire().heat) * self.metrics.casts[slot]
                })
                .sum();
        }
        self.metrics
    }
}
