//! The loot-distribution simulation (`--loot-sim`): how often a drop is pre-sharpened.
//!
//! It rolls the game's own [`engine_game::loot::roll_equipment`] with the shipped
//! `loot.json` rules - the same item pick, quality draw and sharpening draw the dungeon uses -
//! many times per drop source and key level, from a fixed seed, and prints what it observed:
//! the chance of each sharpening level, the mean, the chance of `+5` or better and `+8` or
//! better, and how many runs a player needs on average to see a `+8`.

use std::fmt::Write as _;

use engine_game::firemage::Rng;
use engine_game::loot::{DropSource, LootRules, roll_equipment};

/// The key levels the report covers.
pub const KEY_LEVELS: [u32; 5] = [1, 5, 10, 15, 20];

/// Ordinary monsters a full Graveyard Crypt clear kills (36 placed plus 2 summoned), for the
/// "per run" estimate of monster drops.
const KILLS_PER_RUN: f32 = 38.0;

/// What one (source, key level) cell observed.
#[derive(Debug, Clone, PartialEq)]
pub struct Cell {
    /// The drop source.
    pub source: DropSource,
    /// The key level.
    pub key_level: u32,
    /// How many items were rolled.
    pub samples: u32,
    /// How many had each sharpening level, index = level.
    pub counts: Vec<u32>,
}

impl Cell {
    /// The observed chance of exactly `+level`, `0..=1`.
    #[must_use]
    pub fn p(&self, level: usize) -> f64 {
        f64::from(self.counts.get(level).copied().unwrap_or(0)) / f64::from(self.samples)
    }

    /// The observed chance of `+level` or better.
    #[must_use]
    pub fn p_at_least(&self, level: usize) -> f64 {
        let hits: u32 = self.counts.iter().skip(level).sum();
        f64::from(hits) / f64::from(self.samples)
    }

    /// The observed mean sharpening level.
    #[must_use]
    pub fn mean(&self) -> f64 {
        let sum: f64 = self
            .counts
            .iter()
            .enumerate()
            .map(|(level, count)| level as f64 * f64::from(*count))
            .sum();
        sum / f64::from(self.samples)
    }
}

/// The items one player gets per run from `source`, on average.
fn items_per_run(rules: &LootRules, source: DropSource) -> f32 {
    match source {
        DropSource::Boss | DropSource::Chest => rules.equipment_per_completion as f32,
        DropSource::Mob | DropSource::Elite => KILLS_PER_RUN * rules.mob.equipment_chance,
        DropSource::Special => 1.0,
    }
}

/// The table `source` rolls from.
fn table_of(rules: &LootRules, source: DropSource) -> &engine_game::loot::LootTable {
    match source {
        DropSource::Mob | DropSource::Elite => &rules.mob.table,
        _ => rules
            .boss_tables
            .first()
            .map_or(&rules.mob.table, |entry| &entry.table),
    }
}

/// Rolls `samples` items for one cell.
#[must_use]
pub fn roll_cell(
    rules: &LootRules,
    source: DropSource,
    key_level: u32,
    samples: u32,
    seed: u64,
) -> Cell {
    let table = table_of(rules, source);
    let mix = (source as u64 + 1) * 0x9E37_79B9 + u64::from(key_level) * 0x85EB_CA6B;
    let mut rng = Rng::new(seed ^ mix);
    let mut counts = vec![0_u32; usize::from(engine_game::character::SHARPENING_CEILING) + 1];
    for _ in 0..samples {
        if let Some((_, props)) =
            roll_equipment(table, rules, source, "graveyard_crypt", key_level, &mut rng)
        {
            counts[usize::from(props.sharpening)] += 1;
        }
    }
    Cell {
        source,
        key_level,
        samples,
        counts,
    }
}

/// Every cell: each source at each [`KEY_LEVELS`] entry.
#[must_use]
pub fn run(rules: &LootRules, samples: u32, seed: u64) -> Vec<Cell> {
    DropSource::ALL
        .into_iter()
        .flat_map(|source| KEY_LEVELS.into_iter().map(move |key| (source, key)))
        .map(|(source, key)| roll_cell(rules, source, key, samples, seed))
        .collect()
}

fn percent(value: f64) -> String {
    let percent = value * 100.0;
    if percent == 0.0 {
        "0".to_owned()
    } else if percent < 0.01 {
        "<0.01".to_owned()
    } else if percent < 1.0 {
        format!("{percent:.2}")
    } else {
        format!("{percent:.1}")
    }
}

/// The markdown report.
#[must_use]
pub fn report(rules: &LootRules, cells: &[Cell], seed: u64) -> String {
    let samples = cells.first().map_or(0, |cell| cell.samples);
    let mut out = String::new();
    let _ = writeln!(out, "# Loot sharpening distribution\n");
    let _ = writeln!(
        out,
        "Generated by `engine-sim --loot-sim` (seed {seed:#x}, {samples} items per source and key \
         level). Every item is rolled with the shipped `assets/catalog/loot.json` rules through \
         `engine_game::loot::roll_equipment`: pick, base quality, then the separate sharpening \
         draw from the curve for its source, key-shifted. The `sharpening_drops` block there is \
         the only source of these numbers; regenerate this file after editing it.\n"
    );
    let _ = writeln!(
        out,
        "Cells are the observed share of items with exactly that sharpening level, in per cent. \
         *Runs to +8* is `1 / (P(>= +8) x items per run)` for one player, with items per run: \
         chest and boss {:.0} (equipment per completion), mob and elite {:.1} ({KILLS_PER_RUN:.0} \
         kills x the equipment chance), special 1. `-` means no +8 was observed in the sample.\n",
        items_per_run(rules, DropSource::Chest),
        items_per_run(rules, DropSource::Mob),
    );
    let levels = cells
        .iter()
        .flat_map(|cell| cell.counts.iter().rposition(|count| *count > 0))
        .max()
        .unwrap_or(0);
    for source in DropSource::ALL {
        let _ = writeln!(out, "## {}\n", source.key());
        let mut header = String::from("| Key |");
        let mut rule = String::from("|---|");
        for level in 0..=levels {
            let _ = write!(header, " +{level} |");
            rule.push_str("---|");
        }
        header.push_str(" Mean | P(>=+5) | P(>=+8) | Runs to +8 |");
        rule.push_str("---|---|---|---|");
        let _ = writeln!(out, "{header}\n{rule}");
        for cell in cells.iter().filter(|cell| cell.source == source) {
            let mut row = format!("| {} |", cell.key_level);
            for level in 0..=levels {
                let _ = write!(row, " {} |", percent(cell.p(level)));
            }
            let at_8 = cell.p_at_least(8);
            let runs = if at_8 > 0.0 {
                format!(
                    "{:.0}",
                    1.0 / (at_8 * f64::from(items_per_run(rules, source)))
                )
            } else {
                "-".to_owned()
            };
            let _ = writeln!(
                row,
                " {:.3} | {} | {} | {runs} |",
                cell.mean(),
                percent(cell.p_at_least(5)),
                percent(at_8),
            );
            out.push_str(&row);
        }
        out.push('\n');
    }
    out
}

#[cfg(test)]
#[allow(clippy::expect_used, reason = "test code asserts on known-good values")]
mod tests {
    use super::*;

    fn rules() -> &'static LootRules {
        engine_realm::loot::builtin_rules().expect("the shipped loot rules build")
    }

    #[test]
    fn observed_frequencies_decrease_and_a_higher_key_raises_the_mean() {
        let rules = rules();
        for source in DropSource::ALL {
            let low = roll_cell(rules, source, 1, 40_000, 7);
            let high = roll_cell(rules, source, 20, 40_000, 7);
            for cell in [&low, &high] {
                // The first four levels are common enough to compare reliably.
                for level in 0..3 {
                    assert!(
                        cell.p(level) > cell.p(level + 1),
                        "{source:?} key {}: +{level} {} vs +{} {}",
                        cell.key_level,
                        cell.p(level),
                        level + 1,
                        cell.p(level + 1)
                    );
                }
            }
            assert!(
                high.mean() > low.mean(),
                "{source:?}: {} vs {}",
                high.mean(),
                low.mean()
            );
        }
    }

    #[test]
    fn a_plus_eight_is_extremely_rare_at_low_keys() {
        let rules = rules();
        for source in DropSource::ALL {
            let cell = roll_cell(rules, source, 1, 40_000, 11);
            assert!(
                cell.p_at_least(8) < 0.005,
                "{source:?}: {}",
                cell.p_at_least(8)
            );
        }
    }

    #[test]
    fn the_same_seed_gives_the_same_report() {
        let rules = rules();
        let a = report(rules, &run(rules, 2_000, 5), 5);
        let b = report(rules, &run(rules, 2_000, 5), 5);
        assert_eq!(a, b);
        assert!(a.contains("## boss"));
    }
}
