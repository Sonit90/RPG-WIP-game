//! The client's network layer.
//!
//! ```text
//!                 game thread                     │            network thread
//!   ┌────────────────────────────────────────┐    │   ┌──────────────────────────────────┐
//!   │ front-end screens, world session       │    │   │ Worker                           │
//!   │   NetworkClient::send(NetCommand) ─────┼────┼──►│  ApiClient  ── HTTPS ─► realm API│
//!   │   NetworkClient::poll() ◄── NetEvent ──┼────┼───│  RealmLink  ── WSS  ─► SpacetimeDB│
//!   │   RealmMirror (plain data)             │    │   │  tokens, reconnect, clock sync   │
//!   │   Prediction / SnapshotBuffer          │    │   └──────────────────────────────────┘
//!   └────────────────────────────────────────┘    │
//! ```
//!
//! What this crate is for: getting authoritative state from the realm to the game thread
//! without the game thread ever waiting, and getting the player's *intent* to the realm. It
//! contains no rendering, no UI and no `windows`; the token store is a trait the game
//! implements over the OS. Everything the game reads is plain data in [`model`] — a renderer
//! that draws a [`model::RemotePlayerState`] does not know a network exists.
//!
//! | Module | Role |
//! | --- | --- |
//! | [`config`] | the four realm addresses, from defaults, a file and the environment |
//! | [`api`] | the realm API over HTTPS (auth, characters, settings, queue) |
//! | [`session`] | the network thread, [`NetworkClient`], commands and events |
//! | [`model`] | the plain-data mirror of the player's slice of the realm |
//! | [`prediction`] | local-player prediction and reconciliation |
//! | [`interpolation`] | remote-entity interpolation |
//! | [`clock`] | the estimate of the server's clock |
//! | [`token_store`] | where a remembered session lives |

