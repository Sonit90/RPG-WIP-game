/// Draws `icon` with its top-left at `origin`, one icon pixel being `cell` screen pixels.
///
/// One rectangle per horizontal run of lit pixels, so the cost is the drawing's complexity
/// and not its area.
pub fn draw(list: &mut UiDrawList, icon: Icon, origin: (f32, f32), cell: f32, color: UiColor) {
    for (row, line) in art(icon).iter().enumerate() {
        let bytes = line.as_bytes();
        let mut column = 0;
        while column < SIZE {
            if bytes.get(column) != Some(&b'x') {
                column += 1;
                continue;
            }
            let start = column;
            while bytes.get(column) == Some(&b'x') {
                column += 1;
            }
            list.rect(
                UiRect::new(
                    origin.0 + start as f32 * cell,
                    origin.1 + row as f32 * cell,
                    (column - start) as f32 * cell,
                    cell,
                ),
                color,
            );
        }
    }
}

/// Draws `icon` centred in `rect`.
pub fn draw_in(list: &mut UiDrawList, icon: Icon, rect: UiRect, cell: f32, color: UiColor) {
    let side = SIZE as f32 * cell;
    draw(
        list,
        icon,
        (
            (rect.x + (rect.width - side) * 0.5).round(),
            (rect.y + (rect.height - side) * 0.5).round(),
        ),
        cell,
        color,
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    const EVERY: [Icon; 43] = [
        Icon::Folder,
        Icon::Model,
        Icon::Material,
        Icon::Texture,
        Icon::Scene,
        Icon::Water,
        Icon::Spawn,
        Icon::Light,
        Icon::Eye,
        Icon::EyeOff,
        Icon::Lock,
        Icon::Unlock,
        Icon::Select,
        Icon::Move,
        Icon::Rotate,
        Icon::Scale,
        Icon::Undo,
        Icon::Redo,
        Icon::Save,
        Icon::Play,
        Icon::Grid,
        Icon::Magnet,
        Icon::World,
        Icon::Local,
        Icon::Search,
        Icon::List,
        Icon::Tiles,
        Icon::ChevronRight,
        Icon::ChevronDown,
        Icon::Close,
        Icon::Warning,
        Icon::Rock,
        Icon::Tree,
        Icon::Cave,
        Icon::Pivot,
        Icon::Place,
        Icon::Sculpt,
        Icon::Keyboard,
        Icon::Chart,
        Icon::Reset,
        Icon::Check,
        Icon::Cube,
        Icon::Dot,
    ];

    #[test]
    fn every_icon_is_nine_by_nine_and_draws_something() {
        for icon in EVERY {
            for line in art(icon) {
                assert_eq!(line.len(), SIZE, "{icon:?}: {line:?}");
            }
            let mut list = UiDrawList::new();
            draw(&mut list, icon, (0.0, 0.0), 1.0, [1.0; 4]);
            assert!(!list.is_empty(), "{icon:?} is blank");
            assert!(list.len() <= 40, "{icon:?} costs {} rectangles", list.len());
        }
    }
}
