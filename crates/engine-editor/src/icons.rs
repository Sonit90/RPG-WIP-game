//! The editor's icons: small pictures drawn from rectangles, in the same pixel grid as its
//! font.
//!
//! # Why not the interface atlas
//!
//! The atlas holds the game's art — ability icons and equipment — and a new picture in it is
//! a change to the renderer's texture. The editor's icons are nine-by-nine pixel drawings,
//! written below as text so they can be read and edited in place, and drawn as one rectangle
//! per horizontal run of lit pixels: a folder is nine rectangles, a cube about twenty. They
//! share the font's crisp, whole-pixel look, which is what makes the editor read as one
//! typeface and one icon set rather than two.

