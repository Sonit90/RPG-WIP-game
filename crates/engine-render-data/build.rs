//! Generates the interface fonts' metrics: advance widths and line metrics per face, from the
//! bundled TTFs in `fonts/`.
//!
//! The metrics live here, in the pure-data crate, so that `engine-presentation` can measure,
//! align and wrap text without linking the renderer. `engine-renderer`'s build script reads the
//! same files with the same crate to rasterize the glyphs, so a string measured here is exactly
//! the width the renderer lays it out at.
//!
//! A build dependency only: the crate itself still depends on `engine-core` alone.

use std::fmt::Write as _;
use std::path::PathBuf;

use ab_glyph::{Font, FontRef};

/// The faces, in `UiFont` order.
const FACES: [&str; 4] = [
    "Inter-Regular.ttf",
    "Inter-Medium.ttf",
    "Inter-SemiBold.ttf",
    "Cinzel-SemiBold.ttf",
];

/// Every character the interface fonts draw. ASCII, and the handful of typographic marks the
/// interface writes: a middle dot, dashes, a curly apostrophe, a multiplication sign, a bullet
/// and an ellipsis. `engine-renderer/build.rs` must use the same list; it reads it from here.
const CHARSET: &str = concat!(
    " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`",
    "abcdefghijklmnopqrstuvwxyz{|}~",
    "\u{00B7}\u{2013}\u{2014}\u{2019}\u{00D7}\u{2022}\u{2026}"
);

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default());
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=fonts");

    let mut generated = String::from("// Generated by build.rs from fonts/*.ttf. Do not edit.\n\n");
    let _ = writeln!(
        generated,
        "/// Every character the interface fonts draw, in glyph order."
    );
    let _ = writeln!(generated, "pub const CHARSET: &str = {CHARSET:?};");
    let _ = writeln!(generated, "/// How many characters that is.");
    let _ = writeln!(
        generated,
        "pub const GLYPH_COUNT: usize = {};",
        CHARSET.chars().count()
    );
    let _ = writeln!(
        generated,
        "/// Line and glyph metrics for each face, in `UiFont` order."
    );
    let _ = writeln!(
        generated,
        "pub static FACES: [FaceMetrics; {}] = [",
        FACES.len()
    );
    for face in FACES {
        let path = manifest.join("fonts").join(face);
        let bytes = std::fs::read(&path)
            .unwrap_or_else(|error| panic!("failed to read {}: {error}", path.display()));
        let font = FontRef::try_from_slice(&bytes)
            .unwrap_or_else(|error| panic!("failed to parse {}: {error}", path.display()));
        let em = font.units_per_em().unwrap_or(1000.0);
        let _ = writeln!(generated, "    FaceMetrics {{");
        let _ = writeln!(
            generated,
            "        ascent: {:?},",
            font.ascent_unscaled() / em
        );
        let _ = writeln!(
            generated,
            "        descent: {:?},",
            -font.descent_unscaled() / em
        );
        let _ = writeln!(
            generated,
            "        line_gap: {:?},",
            font.line_gap_unscaled() / em
        );
        let _ = write!(generated, "        advances: [");
        for character in CHARSET.chars() {
            let id = font.glyph_id(character);
            assert!(
                id.0 != 0 || character == ' ',
                "{face} has no glyph for {character:?}"
            );
            let _ = write!(generated, "{:?}, ", font.h_advance_unscaled(id) / em);
        }
        let _ = writeln!(generated, "],");
        let _ = writeln!(generated, "    }},");
    }
    let _ = writeln!(generated, "];");
    std::fs::write(out.join("font_metrics.rs"), generated)
        .unwrap_or_else(|error| panic!("failed to write font_metrics.rs: {error}"));
}
